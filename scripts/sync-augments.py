"""Vendor Arena/Mayhem augment names and small icons from CommunityDragon.

The League client stores ARAM Mayhem augments in cherry-augments.json alongside Arena ones,
and many Mayhem augments reuse Arena icons, so the whole catalogue is vendored. Pinned to a
patch so normal builds stay offline and reproducible. Run: python scripts/sync-augments.py
"""
import concurrent.futures
import hashlib
import json
import re
import sys
import time
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

sys.dont_write_bytecode = True
VERSION = '16.20'
ROOT = Path(__file__).resolve().parents[1]
BASE = f'https://raw.communitydragon.org/{VERSION}/plugins/rcp-be-lol-game-data/global/'
ICON_PREFIX = '/lol-game-data/assets/'
PNG = b'\x89PNG\r\n\x1a\n'
RARITIES = {'kSilver': 'silver', 'kGold': 'gold', 'kPrismatic': 'prismatic'}


def download(url):
    for attempt in range(3):
        try:
            request = urllib.request.Request(url, headers={'User-Agent': 'RiftReviewAssetSync/2.0'})
            with urllib.request.urlopen(request, timeout=30) as response:
                return response.read()
        except (OSError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(attempt + 1)


def catalogue(locale):
    return {entry['id']: entry for entry in json.loads(download(f'{BASE}{locale}/v1/cherry-augments.json'))}


def icon_url(path):
    if not isinstance(path, str) or not path.startswith(ICON_PREFIX) or not path.endswith('.png'):
        raise ValueError(f'Unexpected augment icon path: {path!r}')
    return BASE + 'default/' + path[len(ICON_PREFIX):].lower()


def clean_name(value):
    # Names are rendered as text; strip markup the client sometimes embeds.
    return re.sub(r'<[^>]*>', '', value or '').strip()


def records(english, vietnamese):
    result = {}
    for augment_id, entry in sorted(english.items()):
        if not isinstance(augment_id, int) or augment_id <= 0:
            raise ValueError(f'Invalid augment id: {augment_id!r}')
        name_en = clean_name(entry.get('nameTRA'))
        name_vi = clean_name(vietnamese.get(augment_id, {}).get('nameTRA')) or name_en
        if not name_en:
            continue
        result[augment_id] = {
            'en': name_en,
            'vi': name_vi,
            'rarity': RARITIES.get(entry.get('rarity')),
            'url': icon_url(entry.get('augmentSmallIconPath')),
        }
    return result


def fetch_icon(item):
    augment_id, record = item
    data = download(record['url'])
    if not data.startswith(PNG):
        raise ValueError(f'Augment {augment_id} icon is not a PNG')
    return augment_id, data


def write_module(entries):
    lines = [
        '// Generated by scripts/sync-augments.py from CommunityDragon. Do not edit by hand.',
        '// Arena and ARAM Mayhem augments share one catalogue (cherry-augments.json).',
        'const AUGMENTS = Object.freeze({',
    ]
    for augment_id, record in entries.items():
        rarity = 'null' if record['rarity'] is None else json.dumps(record['rarity'])
        lines.append(
            f"  {augment_id}: {{vi: {json.dumps(record['vi'], ensure_ascii=False)}, "
            f"en: {json.dumps(record['en'], ensure_ascii=False)}, rarity: {rarity}}},"
        )
    lines += [
        '});',
        '',
        'export function augmentAsset(id, language = \'vi\') {',
        '  if (!Number.isSafeInteger(id) || !Object.hasOwn(AUGMENTS, id)) return null;',
        '  const augment = AUGMENTS[id];',
        "  return {name: language === 'en' ? augment.en : augment.vi, rarity: augment.rarity, src: `/augments/${id}.png`};",
        '}',
        '',
    ]
    (ROOT / 'public' / 'augment-assets.js').write_text('\n'.join(lines), encoding='utf-8', newline='\n')


def main():
    entries = records(catalogue('en_gb'), catalogue('vi_vn'))
    folder = ROOT / 'public' / 'augments'
    folder.mkdir(exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        icons = dict(pool.map(fetch_icon, entries.items()))
    for old in folder.glob('*.png'):
        old.unlink()
    sources = {}
    for augment_id, data in sorted(icons.items()):
        (folder / f'{augment_id}.png').write_bytes(data)
        sources[str(augment_id)] = {
            'english': entries[augment_id]['en'],
            'url': entries[augment_id]['url'],
            'sha256': hashlib.sha256(data).hexdigest(),
        }
    write_module(entries)
    manifest = {
        'version': VERSION,
        'source': BASE,
        'retrievedAt': datetime.now(timezone.utc).isoformat(),
        'augments': sources,
    }
    (ROOT / 'scripts' / 'augment-icon-sources.json').write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n'
    )
    print(f'Vendored {len(icons)} augment icons and names from CommunityDragon {VERSION}.')


if __name__ == '__main__':
    main()
