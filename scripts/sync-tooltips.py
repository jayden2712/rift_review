"""Vendor item and augment descriptions for hover tooltips from CommunityDragon.

Items come from the client's items.json; augment text comes from the game string table,
where Mayhem augments use several key patterns. Text is reduced to plain lines: markup,
inline icons and unresolved value placeholders (shown as X) never reach the page.
Run: python scripts/sync-tooltips.py
"""
import html
import json
import re
import sys
import time
import urllib.request
from pathlib import Path

sys.dont_write_bytecode = True
VERSION = '16.20'
ROOT = Path(__file__).resolve().parents[1]
BASE = f'https://raw.communitydragon.org/{VERSION}/'
LOCALES = {'vi': ('vi_vn', 'vi_vn'), 'en': ('en_gb', 'en_us')}
MAX_LENGTH = 700


def download(url):
    for attempt in range(3):
        try:
            request = urllib.request.Request(url, headers={'User-Agent': 'RiftReviewAssetSync/2.0'})
            with urllib.request.urlopen(request, timeout=120) as response:
                return response.read()
        except (OSError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(attempt + 1)


def string_table(game_locale):
    # CommunityDragon stores every locale's table under data/menu/en_us/.
    data = json.loads(download(f'{BASE}game/{game_locale}/data/menu/en_us/lol.stringtable.json'))
    entries = data.get('entries', data)
    return {key.lower(): value for key, value in entries.items() if isinstance(value, str)}


def resolve_references(text, table, depth=0):
    def replace(match):
        key = match.group(1).strip().lower()
        if depth < 3 and key in table:
            return resolve_references(table[key], table, depth + 1)
        return ''

    return re.sub(r'\{\{\s*([^}@]+?)\s*(?:@[^}]*)?\}\}', replace, text)


def clean(text, table=None):
    if table is not None:
        text = resolve_references(text, table)
    text = re.sub(r'<flavorText>.*?</flavorText>', '', text, flags=re.S | re.I)
    text = re.sub(r'%i:[A-Za-z0-9_]+%', '', text)
    text = re.sub(r'@[^@\s]{1,80}@', 'X', text)
    text = re.sub(r'<br\s*/?>|</li>|</p>', '\n', text, flags=re.I)
    text = re.sub(r'<li>', '• ', text, flags=re.I)
    text = re.sub(r'<[^>]+>', '', text)
    text = html.unescape(text)
    text = re.sub(r'[ \t]+', ' ', text)
    text = re.sub(r' *\n *', '\n', text)
    text = re.sub(r'\n{3,}', '\n\n', text).strip()
    return text[:MAX_LENGTH].rstrip()


def augment_keys(api_name):
    name = api_name.lower()
    bare = re.sub(r'^(aram_|upgrade_|quest_)', '', name)
    return [
        f'kiwi_{name}_summary', f'kiwi_aram_{bare}_summary', f'kiwi_{bare}_summary',
        f'kiwi_{bare}_tooltipsummary', f'cherry_{bare}_summary', f'augment_{bare}_desc',
        f'{name}_description', f'{bare}_description', f'quest_{bare}_description',
        f'kiwi_{name}_tooltip', f'kiwi_aram_{bare}_tooltip', f'kiwi_{bare}_tooltip',
        f'cherry_{bare}_tooltip', f'augment_{bare}_tooltip', f'{bare}_tooltip',
    ]


def augment_text(api_name, table):
    for key in augment_keys(api_name):
        value = table.get(key)
        if value:
            text = clean(value, table)
            if text:
                return text
    return None


def item_records(items):
    records = {}
    for item in items:
        item_id, name = item.get('id'), clean(item.get('name') or '')
        if not isinstance(item_id, int) or item_id <= 0 or not name:
            continue
        records[str(item_id)] = {'name': name, 'text': clean(item.get('description') or ''), 'price': item.get('priceTotal') or 0}
    return records


def write_module(language, items, augments):
    body = json.dumps({'item': items, 'augment': augments}, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
    path = ROOT / 'public' / f'tooltip-text-{language}.js'
    path.write_text(
        '// Generated by scripts/sync-tooltips.py from CommunityDragon ' + VERSION + '. Do not edit by hand.\n'
        f'export default {body};\n',
        encoding='utf-8',
        newline='\n',
    )
    return path


def main():
    augments = json.loads(download(f'{BASE}plugins/rcp-be-lol-game-data/global/default/v1/cherry-augments.json'))
    for language, (client_locale, game_locale) in LOCALES.items():
        items = json.loads(download(f'{BASE}plugins/rcp-be-lol-game-data/global/{client_locale}/v1/items.json'))
        table = string_table(game_locale)
        augment_texts = {}
        for augment in augments:
            text = augment_text(str(augment.get('augmentNameId') or ''), table)
            if isinstance(augment.get('id'), int) and text:
                augment_texts[str(augment['id'])] = text
        path = write_module(language, item_records(items), augment_texts)
        print(f'{language}: {len(augment_texts)}/{len(augments)} augment descriptions -> {path.name}')


if __name__ == '__main__':
    main()
